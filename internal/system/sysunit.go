// Systemd unit rendering and installation: the oneshot unit that
// materializes the encrypted compose-sops age key onto tmpfs at boot.

package system

import (
	"fmt"
	"path/filepath"
)

// GenerateUnit renders the unit file contents. credPath is the encrypted
// credential to decrypt, credName the credential name it was encrypted with
// (validated by systemd-creds decrypt at boot), and keyPath where the
// plaintext key is materialized on tmpfs. The runtime directory is derived
// from keyPath's parent, falling back to the default when keyPath is not
// directly under /run.
func GenerateUnit(credPath, credName, keyPath string) string {
	return fmt.Sprintf(`# Generated by compose-sops. Materializes the age identity used to decrypt
# SOPS secret files onto tmpfs at boot, so the Compose provider can read it
# from %s. The credential name must match the name the credential was
# encrypted with (see 'compose-sops cred').
[Unit]
Description=Materialize the compose-sops age key on tmpfs
Documentation=man:systemd-creds(1)
Wants=systemd-tpm2-setup.service
After=systemd-tpm2-setup.service

[Service]
Type=oneshot
RemainAfterExit=yes
UMask=0077
RuntimeDirectory=%s
RuntimeDirectoryMode=0700
ExecStart=/usr/bin/systemd-creds decrypt --name="%s" "%s" "%s"

[Install]
WantedBy=multi-user.target
`,
		keyPath,
		runtimeDirName(keyPath),
		credName,
		credPath,
		keyPath)
}

func runtimeDirName(keyPath string) string {
	parent := filepath.Dir(keyPath)
	if filepath.Dir(parent) == "/run" {
		return filepath.Base(parent)
	}
	return filepath.Base(RuntimeDir)
}

// InstallUnit writes the unit to path (0644, atomic replace, symlinks
// refused) and returns the unit file's base name for systemctl operations.
func InstallUnit(unitPath, content string) (string, error) {
	if err := ReplaceFile(unitPath, []byte(content), 0o644); err != nil {
		return "", fmt.Errorf("cannot write unit file %s: %w", unitPath, err)
	}
	return filepath.Base(unitPath), nil
}
